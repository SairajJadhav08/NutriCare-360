import { useRef, useEffect, useState } from 'react'
import Modal from './Modal'

const FONT = "'Inter', system-ui, -apple-system, 'Segoe UI', sans-serif"

/**
 * HealthCard — renders a shareable weekly summary card onto a <canvas>
 * and provides a download button.
 *
 * Props:
 *   username      {string}
 *   stats         { reminders, prescriptions, nutrition, yoga_streak }
 *   calorieGoal   {number}
 *   totalCalories {number}  — calories logged today
 */
export default function HealthCard({ username, stats, calorieGoal, totalCalories, onClose }) {
  const canvasRef = useRef(null)
  const [dataUrl, setDataUrl] = useState(null)

  useEffect(() => {
    const canvas  = canvasRef.current
    if (!canvas) return
    let cancelled = false
    // Wait for Inter and the logo mark so the exported PNG never has fallback text or a blank logo
    const logo = new Image()
    const logoReady = new Promise(res => { logo.onload = res; logo.onerror = res })
    logo.src = '/images/logo-mark-128.webp'
    Promise.all([document.fonts?.ready || Promise.resolve(), logoReady]).then(() => { if (!cancelled) draw() })
    return () => { cancelled = true }

    function draw() {
    const ctx     = canvas.getContext('2d')
    const W = 700, H = 380
    canvas.width  = W
    canvas.height = H

    // ── background ────────────────────────────────────────────────
    const bg = ctx.createLinearGradient(0, 0, W, H)
    bg.addColorStop(0, '#0f172a')
    bg.addColorStop(1, '#1e293b')
    ctx.fillStyle = bg
    ctx.beginPath()
    roundRect(ctx, 0, 0, W, H, 24)
    ctx.fill()

    // ── accent bar left ───────────────────────────────────────────
    const accent = ctx.createLinearGradient(0, 0, 0, H)
    accent.addColorStop(0, '#e11d48')
    accent.addColorStop(1, '#f97316')
    ctx.fillStyle = accent
    ctx.beginPath()
    roundRect(ctx, 0, 0, 6, H, [6, 0, 0, 6])
    ctx.fill()

    // ── logo + title: mark, then the wordmark in its three colours ─
    if (logo.complete && logo.naturalWidth) ctx.drawImage(logo, 32, 26, 42, 42)
    ctx.font = `bold 18px ${FONT}`
    let wx = 86
    for (const [part, color] of [['Nutri', '#ffffff'], ['Care', '#fb7185'], ['-360', '#4cc173']]) {
      ctx.fillStyle = color
      ctx.fillText(part, wx, 46)
      wx += ctx.measureText(part).width
    }

    ctx.fillStyle = '#94a3b8'
    ctx.font      = `13px ${FONT}`
    ctx.fillText('Weekly Health Summary', 86, 65)

    // ── username ──────────────────────────────────────────────────
    ctx.fillStyle = '#f8fafc'
    ctx.font      = `bold 28px ${FONT}`
    ctx.fillText(`@${username}`, 32, 108)

    // ── date ──────────────────────────────────────────────────────
    ctx.fillStyle = '#64748b'
    ctx.font      = `12px ${FONT}`
    const now = new Date()
    ctx.fillText(now.toLocaleDateString('en-US', { weekday:'long', month:'long', day:'numeric', year:'numeric' }), 32, 128)

    // ── divider ───────────────────────────────────────────────────
    ctx.strokeStyle = '#334155'
    ctx.lineWidth   = 1
    ctx.beginPath()
    ctx.moveTo(32, 148)
    ctx.lineTo(W - 32, 148)
    ctx.stroke()

    // ── stat boxes ───────────────────────────────────────────────
    const boxes = [
      { label: 'Reminders',     value: stats.reminders,    color: '#e11d48' },
      { label: 'Prescriptions', value: stats.prescriptions, color: '#0ea5e9' },
      { label: 'Meals Logged',  value: stats.nutrition,    color: '#f59e0b' },
      { label: 'Active Days',   value: `${stats.yoga_streak ?? 0}/7`, color: '#8b5cf6' },
    ]
    const boxW = (W - 64 - 24) / 4
    boxes.forEach((box, i) => {
      const x = 32 + i * (boxW + 8)
      const y = 170

      // box background
      ctx.fillStyle = 'rgba(255,255,255,0.05)'
      roundRect(ctx, x, y, boxW, 100, 12)
      ctx.fill()

      // color key
      ctx.fillStyle = box.color
      ctx.beginPath()
      ctx.arc(x + 20, y + 24, 5, 0, Math.PI * 2)
      ctx.fill()

      // value
      ctx.fillStyle = box.color
      ctx.font      = `bold 26px ${FONT}`
      ctx.fillText(String(box.value), x + 14, y + 64)

      // label
      ctx.fillStyle = '#94a3b8'
      ctx.font      = `11px ${FONT}`
      ctx.fillText(box.label, x + 14, y + 82)
    })

    // ── calorie progress bar ──────────────────────────────────────
    const barY = 296
    ctx.fillStyle = '#1e293b'
    roundRect(ctx, 32, barY, W - 64, 18, 9)
    ctx.fill()

    const pct  = Math.min(1, totalCalories / calorieGoal)
    const barColor = pct >= 1 ? '#ef4444' : pct >= 0.8 ? '#f59e0b' : '#22c55e'
    ctx.fillStyle = barColor
    roundRect(ctx, 32, barY, Math.max(18, (W - 64) * pct), 18, 9)
    ctx.fill()

    ctx.fillStyle = '#94a3b8'
    ctx.font      = `12px ${FONT}`
    ctx.fillText(`Calories today: ${Math.round(totalCalories)} / ${calorieGoal} kcal`, 32, barY - 8)

    // ── footer ────────────────────────────────────────────────────
    ctx.fillStyle = '#475569'
    ctx.font      = `11px ${FONT}`
    ctx.fillText('Generated by NutriCare-360', 32, H - 20)

    setDataUrl(canvas.toDataURL('image/png'))
    }
  }, [username, stats, calorieGoal, totalCalories])

  const handleDownload = () => {
    const a = document.createElement('a')
    a.href     = dataUrl
    a.download = `nutricare360-${username}-${new Date().toISOString().slice(0,10)}.png`
    a.click()
  }

  return (
    <Modal
      title="Health card"
      onClose={onClose}
      width={760}
      footer={
        <>
          <button className="btn btn-ghost" onClick={onClose}>Close</button>
          <button className="btn btn-primary" onClick={handleDownload} disabled={!dataUrl}>
            <i className="fa-solid fa-download" /> Download PNG
          </button>
        </>
      }
    >
      <canvas ref={canvasRef} style={{ width: '100%', borderRadius: '12px', display: 'block' }} />
    </Modal>
  )
}

// helper — rounded rect path
function roundRect(ctx, x, y, w, h, r) {
  if (typeof r === 'number') r = [r, r, r, r]
  const [tl, tr, br, bl] = r
  ctx.beginPath()
  ctx.moveTo(x + tl, y)
  ctx.lineTo(x + w - tr, y)
  ctx.quadraticCurveTo(x + w, y, x + w, y + tr)
  ctx.lineTo(x + w, y + h - br)
  ctx.quadraticCurveTo(x + w, y + h, x + w - br, y + h)
  ctx.lineTo(x + bl, y + h)
  ctx.quadraticCurveTo(x, y + h, x, y + h - bl)
  ctx.lineTo(x, y + tl)
  ctx.quadraticCurveTo(x, y, x + tl, y)
  ctx.closePath()
}
